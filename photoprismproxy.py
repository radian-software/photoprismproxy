import hashlib
import io
import os
from pathlib import Path
import random
import string
from typing import Tuple
from urllib.parse import urlencode

import dotenv
import flask
import requests

dotenv.load_dotenv()


global_uploads_memory = {}


class Config:
    URL = os.environ["PHOTOPRISM_URL"]
    USERNAME = os.environ["PHOTOPRISM_USERNAME"]
    PASSWORD = os.environ["PHOTOPRISM_PASSWORD"]
    MAX_SIZE = int(os.environ["MAX_UPLOAD_BYTES"])
    AUTH_SECRET = os.environ["AUTH_SECRET"]


class PhotoPrism:
    def __init__(self, url: str, username: str, password: str):
        self.url = url.rstrip("/")
        self.username = username
        self.password = password
        self.headers = {
            "Authorization": f"Bearer {self.password}",
        }
        self.user_id, self.preview_token = self.get_user_info()

    def get_user_info(self) -> Tuple[str, str]:
        resp = requests.get(
            self.url + "/api/v1/session",
            headers=self.headers,
        )
        resp.raise_for_status()
        data = resp.json()
        return data["user"]["UID"], data["config"]["previewToken"]

    def generate_token(self) -> str:
        # https://github.com/photoprism/photoprism/blob/f652159522f992a56ea918db90275dd2257a5664/frontend/src/common/util.js#L294-L296
        # but less scuffed, cf https://github.com/photoprism/photoprism/issues/4970
        return "".join(random.choices(string.ascii_lowercase + string.digits, k=7))

    def upload_photos(self, photos, album=None) -> Tuple[str, list[str], str | None]:
        route = f"/api/v1/users/{self.user_id}/upload/{self.generate_token()}"
        hashes = []
        for idx, photo in enumerate(photos):
            data = photo.read()
            h = hashlib.sha1()
            h.update(data)
            hashes.append(h.hexdigest())
            # The filename is actually critical here. The reason why is a giant
            # mess. It's because PhotoPrism (still, in 2026) doesn't offer any
            # way to control the sorting of albums in a reasonable way. You can
            # only key off properties of the underlying photos, not anything
            # about when they were added to the album. The oldest and newest
            # orders are useless as they are affected by EXIF data that we don't
            # want to wipe out in our uploaded photos. The recently added order
            # is usable, but it requires the photos to be uploaded in reverse
            # order, so they'll show up weird in the library. Ordering by
            # filename is pointless because the filenames are automatically
            # generated by PhotoPrism and do not correspond reliably to upload
            # order. (For future reference: the filename format, at least by
            # default, is YYYYMMDD_HHMMSS_CHECKSUM, where CHECKSUM is the CRC-32
            # using Castagnoli polynomial, in uppercase hex. So, if we waited
            # more than a second between uploads, then technically it works, but
            # that is really stupid and we shouldn't count on it.) Anyway what
            # we have to do instead is title ordering. Note that title ordering
            # also falls back to filename ordering if the titles are the same so
            # we really have to get it right. Unfortunately there is a
            # complicated algorithm involving lots of regexes and English
            # dictionary lookups(!) to generate "normal-looking" titles from
            # provided filenames in PhotoPrism, so we have to sort of trick the
            # algorithm into letting us specify unique sequential titles based
            # on the filenames. In particular, a regex splits the filename on
            # things like underscores, any three-letter phrases that aren't
            # English words get removed, as do any sequences that are just
            # numeric. Hence using "proxy" instead of "ppp", and sticking a
            # letter in front of the upload index. Check file_title.go in
            # PhotoPrism for the implementation.
            resp = requests.post(
                self.url + route,
                headers=self.headers,
                files={
                    "files": (
                        f"proxy_upload_n{idx:05d}" + Path(photo.filename).suffix,
                        io.BytesIO(data),
                    ),
                },
            )
            resp.raise_for_status()
            if not resp.json()["message"].startswith("1 file"):
                raise RuntimeError(f"Got unexpected server response: {resp.json()}")
        resp = requests.put(
            self.url + route,
            headers=self.headers,
            json={"albums": [album] if album else []},
        )
        resp.raise_for_status()
        resp = requests.get(
            self.url
            + "/api/v1/photos?"
            + urlencode(
                {
                    "count": "1000",
                    "q": "hash:" + "|".join(hashes),
                }
            ),
            headers=self.headers,
        )
        resp.raise_for_status()
        photo_urls = [
            f"{self.url}/api/v1/t/{photo['Hash']}/{self.preview_token}/fit_4096"
            for photo in resp.json()
        ]
        assert len(photo_urls) == len(
            photos
        ), f"{len(photo_urls)} urls for {len(photos)} photos"
        album_url = None
        if album:
            resp = requests.get(
                self.url
                + "/api/v1/albums?"
                + urlencode(
                    {
                        "count": "2",
                        "q": album,
                        "type": "album",
                    }
                ),
                headers=self.headers,
            )
            resp.raise_for_status()
            matching_albums = resp.json()
            assert len(matching_albums) <= 1, len(matching_albums)
            if matching_albums:
                album_id = matching_albums[0]["UID"]
            else:
                resp = requests.post(
                    self.url + "/api/v1/albums",
                    headers=self.headers,
                    json={"Title": album},
                )
                resp.raise_for_status()
                album_id = resp.json()["UID"]
            resp = requests.put(
                self.url + "/api/v1/albums/" + album_id,
                headers=self.headers,
                json={"Order": "title"},
            )
            resp.raise_for_status()
            resp = requests.get(
                self.url + f"/api/v1/albums/{album_id}/links",
                headers=self.headers,
            )
            resp.raise_for_status()
            album_token = album_slug = None
            for link in resp.json():
                if link["Expires"] == 0:
                    album_token = link["Token"]
                    album_slug = link["Slug"]
                    break
            if not album_token:
                slug = self.generate_token()
                resp = requests.post(
                    self.url + f"/api/v1/albums/{album_id}/links",
                    headers=self.headers,
                    json={"Slug": slug},
                )
                resp.raise_for_status()
                album_token = resp.json()["Token"]
                album_slug = slug
            album_url = f"{self.url}/s/{album_token}/{album_slug}"
        upload_id = self.generate_token()
        return upload_id, photo_urls, album_url


pp = PhotoPrism(Config.URL, Config.USERNAME, Config.PASSWORD)

app = flask.Flask(__name__, template_folder="pages")
app.config["MAX_CONTENT_LENGTH"] = Config.MAX_SIZE


@app.before_request
def require_login():
    token = flask.request.cookies.get("auth-token")
    if token != Config.AUTH_SECRET:
        resp = flask.send_from_directory("pages", "auth.html")
        resp.status_code = 401
        return resp


@app.get("/")
def get_index():
    return flask.send_from_directory("pages", "index.html")


@app.post("/upload")
def post_upload():
    form = flask.request.form
    photos = flask.request.files.getlist("photos")
    if not photos:
        return flask.abort(400)
    if not all(photo.filename for photo in photos):
        return flask.abort(400)
    match form["sort"]:
        case "none":
            pass
        case "asc":
            photos.sort(key=lambda f: f.filename or "")
        case "desc":
            photos.sort(key=lambda f: f.filename or "", reverse=True)
        case _:
            return flask.abort(400)
    upload_id, photo_urls, album_url = pp.upload_photos(photos, album=form["album"])
    global_uploads_memory[upload_id] = photo_urls, album_url
    return flask.redirect(f"/success/{upload_id}")


@app.route("/success/<upload_id>", methods=["HEAD", "GET", "POST"])
def get_success(upload_id: str):
    if upload_id not in global_uploads_memory:
        return flask.abort(404)
    photo_urls, album_url = global_uploads_memory[upload_id]
    return flask.render_template(
        "success.html", photo_urls=photo_urls, album_url=album_url
    )
